def cross_validate(splits):
    # Run the FINAL 3D system (SGD floor -> KNN position) on every fold and average the results
    rows = []
    for tr, te in splits:
        fp_, xp_ = predict_3d(tr, te, make_sgd(), lambda: make_knn(best_k))
        rows.append(summarize_3d(te, fp_, xp_))
    return pd.DataFrame(rows).mean().to_dict()

