def make_sgd():
    # Floor classifier (same settings as in Step 4)
    return Pipeline([("scaler", StandardScaler()),
                     ("sgd", SGDClassifier(loss="log_loss", alpha=1e-3, max_iter=2000, tol=1e-4,
                                           random_state=RANDOM_STATE))])

def make_knn(k=3):
    # Position regressor: average of the k most similar fingerprints (closer ones count more)
    return Pipeline([("scaler", StandardScaler()),
                     ("knn", KNeighborsRegressor(n_neighbors=k, weights="distance"))])

def predict_3d(tr, te, floor_model=None, make_regressor=make_knn):
    # Predict floor and position inside the floor for the locations `te`, learning only from `tr`.
    # floor_model=None means "oracle": the true floor is used.
    if floor_model is None:
        floor_pred = y_floor[te]
    else:
        floor_pred = floor_model.fit(X.iloc[tr], y_floor[tr]).predict(X.iloc[te])
    xy_pred = np.zeros((len(te), 2))
    for f in floors:                                   # stage 2: one regressor per (predicted) floor
        mask = floor_pred == f
        if mask.sum() == 0:
            continue
        tr_f = tr[y_floor[tr] == f]
        xy_pred[mask] = make_regressor().fit(X.iloc[tr_f], local_xy[tr_f]).predict(X.iloc[te][mask])
    return floor_pred, xy_pred

def errors_3d(te, floor_pred, xy_pred):
    # Per-location errors
    err_2d = np.sqrt(((xy_pred - local_xy[te]) ** 2).sum(axis=1))
    err_3d = np.sqrt(err_2d ** 2 + ((floor_pred - y_floor[te]) * FLOOR_HEIGHT) ** 2)
    return err_2d, err_3d

def summarize_3d(te, floor_pred, xy_pred):
    err_2d, err_3d = errors_3d(te, floor_pred, xy_pred)
    right = floor_pred == y_floor[te]
    return {"Floor accuracy": right.mean(),
            "2D error mean": err_2d.mean(), "2D error median": np.median(err_2d),
            "2D error 90th pct": np.percentile(err_2d, 90),
            "2D error (correct floor only)": err_2d[right].mean(),
            "3D error mean": err_3d.mean(), "3D error median": np.median(err_3d)}

# ---- 1) choose k with cross-validation on the TRAINING locations only (twin-safe) ----
inner = StratifiedGroupKFold(5, shuffle=True, random_state=RANDOM_STATE)
