def twin_safe_split(seed, test_fraction=0.2):
    # Split the locations into train/test so that
    #  - every floor is represented in both sets,
    #  - locations with identical fingerprints (twins) are never separated.
    rng = np.random.RandomState(seed)
    test_groups = []
    for floor in floors:
        groups_on_floor = np.unique(twin_group[y_floor == floor])
        n_test = int(round(test_fraction * len(groups_on_floor)))
        test_groups += list(rng.choice(groups_on_floor, size=n_test, replace=False))
    is_test = np.isin(twin_group, test_groups)
    return np.where(~is_test)[0], np.where(is_test)[0]

